#!/usr/bin/env python3
"""Generate the control protocol's code and OpenAPI description from
protocol/control.yaml.

    gen-protocol.py           write the outputs
    gen-protocol.py --check   exit 1 when an output differs from what it would write

Outputs:
    src/mp_api/ControlProtocol.h   tables for the program
    resources/web/openapi.json     the HTTP API
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "protocol" / "control.yaml"
HEADER = ROOT / "src" / "mp_api" / "ControlProtocol.h"
OPENAPI = ROOT / "resources" / "web" / "openapi.json"


def ident(name):
    """camelCase or kebab-case to UpperCamel for C++ enumerators."""
    parts = name.replace("-", " ").replace("_", " ").split()
    out = []
    for p in parts:
        out.append(p[0].upper() + p[1:])
    return "".join(out)


def cstr(s):
    return json.dumps(s or "")


def header(spec):
    p = spec["protocol"]
    L = []
    w = L.append
    w("// Generated by tools/gen-protocol.py from protocol/control.yaml. Do not edit.")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("#include <string_view>")
    w("")
    w("namespace mp::api {")
    w("")
    w(f"constexpr int kMajor = {p['major']};")
    w(f"constexpr int kMinor = {p['minor']};")
    w(f"constexpr std::string_view kProtocolName = {cstr(p['name'])};")
    w("")

    # Types.
    w("enum class Type : uint8_t {")
    for t in spec["types"]:
        w(f"  {ident(t['name'])} = {t['code']},")
    w("};")
    w("")
    w("enum class Access : uint8_t { Read, Set, Press };")
    w("enum class Dump : uint8_t { None, Bits, Values };")
    w("")
    w("struct TypeInfo {")
    w("  Type type;")
    w("  std::string_view name;")
    w("  std::string_view plural;")
    w("  Access access;")
    w("  Dump dump;")
    w("  bool hasValue;")
    w("  int min, max;")
    w("  bool toggles;  // a Set of 2 toggles")
    w("  std::string_view doc;")
    w("};")
    w("")
    w(f"constexpr TypeInfo kTypes[] = {{")
    for t in spec["types"]:
        v = t.get("value")
        access = {"read": "Read", "set": "Set", "press": "Press"}[t["access"]]
        dump = {"bits": "Bits", "values": "Values", None: "None"}[t.get("dump")]
        w(f"  {{Type::{ident(t['name'])}, {cstr(t['name'])}, {cstr(t['plural'])}, Access::{access}, "
          f"Dump::{dump}, {'true' if v else 'false'}, {v['min'] if v else 0}, {v['max'] if v else 0}, "
          f"{'true' if v and 'toggle' in v else 'false'}, {cstr(t.get('doc'))}}},")
    w("};")
    w("")
    w("constexpr const TypeInfo* typeInfo(Type t) {")
    w("  for (const auto& i : kTypes)")
    w("    if (i.type == t) return &i;")
    w("  return nullptr;")
    w("}")
    w("constexpr const TypeInfo* typeByPlural(std::string_view plural) {")
    w("  for (const auto& i : kTypes)")
    w("    if (i.plural == plural) return &i;")
    w("  return nullptr;")
    w("}")
    w("")

    # Object properties.
    w("enum class Prop : uint8_t {")
    for pr in spec["properties"]:
        w(f"  {ident(pr['name'])} = {pr['code']},")
    w("};")
    w("")
    roles = next(pr["values"] for pr in spec["properties"] if pr["name"] == "role")
    w("enum class Role : uint8_t {")
    for i, r in enumerate(roles):
        w(f"  {ident(r)} = {i},")
    w("};")
    w(f"constexpr std::string_view kRoleNames[] = {{{', '.join(cstr(r) for r in roles)}}};")
    w("")

    # Program properties.
    w("enum class ProgramProp : uint8_t {")
    for pp in spec["program"]:
        w(f"  {ident(pp['name'])} = {pp['index']},")
    w("};")
    w("")
    w("struct ProgramPropInfo {")
    w("  ProgramProp prop;")
    w("  std::string_view name;")
    w("  int min, max;")
    w("  bool writable;")
    w("  std::string_view doc;")
    w("};")
    w("constexpr ProgramPropInfo kProgram[] = {")
    for pp in spec["program"]:
        w(f"  {{ProgramProp::{ident(pp['name'])}, {cstr(pp['name'])}, {pp['min']}, {pp['max']}, "
          f"{'true' if pp['access'] == 'set' else 'false'}, {cstr(pp.get('doc'))}}},")
    w("};")
    w(f"constexpr int kProgramCount = {len(spec['program'])};")
    w("")

    # Commands.
    w("enum class Command : uint8_t {")
    for c in spec["commands"]:
        w(f"  {ident(c['name'])} = {c['index']},")
    w("};")
    w(f"constexpr std::string_view kCommandNames[] = {{{', '.join(cstr(c['name']) for c in spec['commands'])}}};")
    w(f"constexpr int kCommandCount = {len(spec['commands'])};")
    w("")

    # Operations.
    w("enum class Op : uint8_t {")
    for o in spec["operations"]:
        w(f"  {ident(o['name'])} = {o['code']},")
    w("};")
    w("")

    # Errors.
    w("enum class Error : uint8_t {")
    w("  None = 0,")
    for e in spec["errors"]:
        w(f"  {ident(e['name'])} = {e['code']},")
    w("};")
    w("struct ErrorInfo {")
    w("  Error error;")
    w("  std::string_view name;")
    w("  int httpStatus;")
    w("};")
    w("constexpr ErrorInfo kErrors[] = {")
    for e in spec["errors"]:
        w(f"  {{Error::{ident(e['name'])}, {cstr(e['name'])}, {e['http']}}},")
    w("};")
    w("constexpr const ErrorInfo* errorInfo(Error e) {")
    w("  for (const auto& i : kErrors)")
    w("    if (i.error == e) return &i;")
    w("  return nullptr;")
    w("}")
    w("")

    # SysEx.
    sx = spec["encodings"]["sysex"]
    w("namespace sysex {")
    w(f"constexpr uint8_t kHeader[] = {{{', '.join(hex(b) for b in sx['header'])}}};")
    w(f"constexpr uint8_t kUnitAll = {sx['unitAll']};")
    w(f"constexpr int kMaxMessage = {sx['maxMessage']};")
    w(f"constexpr int kDumpBits = {sx['dumpBits']};")
    w(f"constexpr int kDumpValues = {sx['dumpValues']};")
    w("}  // namespace sysex")
    w("")
    w("}  // namespace mp::api")
    w("")
    return "\n".join(L)


def openapi(spec):
    p = spec["protocol"]
    errors = {e["name"]: e["http"] for e in spec["errors"]}
    plural_types = [t for t in spec["types"] if t["name"] != "program"]
    type_enum = [t["plural"] for t in plural_types]

    def error_responses():
        out = {}
        for name, status in sorted(errors.items(), key=lambda kv: kv[1]):
            out.setdefault(str(status), {"description": name, "content": {
                "application/json": {"schema": {"$ref": "#/components/schemas/Error"}}}})
        return out

    type_param = {"name": "type", "in": "path", "required": True,
                  "schema": {"type": "string", "enum": type_enum}}
    index_param = {"name": "index", "in": "path", "required": True,
                   "schema": {"type": "integer", "minimum": 0}}
    session_header = {"name": "X-Session", "in": "header", "required": False,
                      "schema": {"type": "integer"},
                      "description": "Refused with stale-session when another organ has loaded since."}
    paths = {
        "/api/v1": {"get": {"summary": "Identify", "operationId": "identify",
                            "responses": {"200": {"description": "The program, the protocol and the session",
                                                  "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Identity"}}}}}}},
        "/api/v1/program": {"get": {"summary": "The program's properties", "operationId": "getProgram",
                                    "responses": {"200": {"description": "Every property with its value",
                                                          "content": {"application/json": {"schema": {"type": "object"}}}}}}},
        "/api/v1/program/{property}": {"put": {
            "summary": "Set a program property", "operationId": "setProgram",
            "parameters": [{"name": "property", "in": "path", "required": True,
                            "schema": {"type": "string",
                                       "enum": [pp["name"] for pp in spec["program"] if pp["access"] == "set"]}},
                           session_header],
            "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Value"}}}},
            "responses": {"200": {"description": "The value now", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Value"}}}},
                          **error_responses()}}},
        "/api/v1/{type}": {"get": {
            "summary": "Count and describe every object of a type", "operationId": "list",
            "parameters": [type_param],
            "responses": {"200": {"description": "The objects, with their properties and values",
                                  "content": {"application/json": {"schema": {"$ref": "#/components/schemas/List"}}}},
                          **error_responses()}}},
        "/api/v1/{type}/values": {"get": {
            "summary": "Dump every value of a type", "operationId": "dump",
            "parameters": [type_param],
            "responses": {"200": {"description": "The values in index order",
                                  "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Dump"}}}},
                          **error_responses()}}},
        "/api/v1/{type}/{index}": {"get": {
            "summary": "Describe one object", "operationId": "describe",
            "parameters": [type_param, index_param],
            "responses": {"200": {"description": "Its properties and value",
                                  "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Object"}}}},
                          **error_responses()}}},
        "/api/v1/{type}/{index}/value": {
            "get": {"summary": "Get a value", "operationId": "get", "parameters": [type_param, index_param],
                    "responses": {"200": {"description": "The value", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Value"}}}},
                                  **error_responses()}},
            "put": {"summary": "Set a value; for a switch, 2 or \"toggle\" toggles", "operationId": "set",
                    "parameters": [type_param, index_param, session_header],
                    "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Value"}}}},
                    "responses": {"200": {"description": "The value now", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Value"}}}},
                                  **error_responses()}}},
        "/api/v1/{type}/{index}/press": {"post": {
            "summary": "Press: a piston, a preset, a temperament or a command", "operationId": "press",
            "parameters": [type_param, index_param, session_header],
            "responses": {"200": {"description": "Done", "content": {"application/json": {"schema": {"type": "object"}}}},
                          **error_responses()}}},
        "/api/v1/events": {"get": {
            "summary": "Every change, as server-sent events", "operationId": "events",
            "parameters": [{"name": "types", "in": "query", "required": False,
                            "schema": {"type": "string"},
                            "description": "Comma-separated plurals to receive; all when absent"}],
            "responses": {"200": {"description": "event: change, data: {type, index, value, session}",
                                  "content": {"text/event-stream": {"schema": {"type": "string"}}}}}}},
    }
    doc = {
        "openapi": "3.1.0",
        "info": {"title": p["name"], "version": f"{p['major']}.{p['minor']}",
                 "description": "Generated from protocol/control.yaml. Object types: " +
                                "; ".join(f"{t['plural']}: {t.get('doc', '')}" for t in plural_types)},
        "paths": paths,
        "components": {
            "securitySchemes": {"token": {"type": "http", "scheme": "bearer"}},
            "schemas": {
                "Error": {"type": "object", "properties": {"error": {"type": "string", "enum": list(errors)}}},
                "Value": {"type": "object", "properties": {"value": {"oneOf": [{"type": "integer"}, {"type": "string", "enum": ["toggle"]}]}}},
                "Identity": {"type": "object"},
                "Object": {"type": "object"},
                "List": {"type": "object"},
                "Dump": {"type": "object"},
            },
        },
        "security": [{}, {"token": []}],
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main():
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    outputs = {HEADER: header(spec), OPENAPI: openapi(spec)}
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs.items():
        # A checkout may have turned the line ends into CRLF.
        old = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else None
        if old != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    for path in stale:
        print(("out of date: " if check else "wrote ") + str(path.relative_to(ROOT)))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
